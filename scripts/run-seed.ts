// نحوه اجرا: npm run seed یا npx tsx scripts/run-seed.ts

import { initDb, sqlite } from '../src/db/index.js';
import { runComprehensiveSeed } from '../src/db/seeds.js';

console.log('========================================================');
console.log('🌱 شروع فرایند سیدینگ دستی پایگاه داده سامانه دانا (DANA)');
console.log('========================================================');

try {
  // اطمینان از مقداردهی اولیه جداول پایگاه داده
  console.log('⏳ در حال بررسی و آماده‌سازی ساختار پایگاه داده...');
  initDb();

  // اجرای سید جامع داده‌ها
  console.log('🚀 در حال بارگذاری داده‌های پایه و سازمانی، درختواره‌ها، گپ‌ها و مسائل...');
  runComprehensiveSeed(sqlite);

  console.log('========================================================');
  console.log('✅ عملیات سیدینگ دستی با موفقیت ۱۰۰٪ به پایان رسید!');
  console.log('🎉 تمام اطلاعات نمونه با موفقیت در پایگاه داده ذخیره شدند.');
  console.log('========================================================');
  process.exit(0);
} catch (error) {
  console.error('❌ خطا در حین اجرای سید دستی:', error);
  process.exit(1);
}
